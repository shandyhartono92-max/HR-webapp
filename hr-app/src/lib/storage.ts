import "server-only";
import { mkdir, readFile as fsReadFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { randomUUID } from "node:crypto";

// Private file storage. Development writes to ./storage (outside /public, so files
// are never served directly). For production, replace these two functions with an
// S3-compatible bucket in an Indonesian region and keep the same signatures.

const ROOT = path.join(process.cwd(), "storage");

export async function saveFile(folder: string, data: Buffer, ext: string): Promise<string> {
  const key = `${folder}/${randomUUID()}.${ext}`;
  const fullPath = path.join(ROOT, key);
  await mkdir(path.dirname(fullPath), { recursive: true });
  await writeFile(fullPath, data);
  return key;
}

export async function readFile(key: string): Promise<Buffer> {
  // Keys are generated by saveFile; refuse anything that tries to leave ROOT
  const fullPath = path.resolve(ROOT, key);
  if (!fullPath.startsWith(ROOT + path.sep)) throw new Error("Invalid storage key");
  return fsReadFile(fullPath);
}

export async function deleteFile(key: string) {
  await rm(path.join(ROOT, key), { force: true });
}

// Check the file's real content, not just its name or the browser's MIME type
export function detectCvType(data: Buffer): { ext: "pdf" | "docx"; mime: string } | null {
  if (data.subarray(0, 5).toString("latin1") === "%PDF-") {
    return { ext: "pdf", mime: "application/pdf" };
  }
  const isZip = data[0] === 0x50 && data[1] === 0x4b && data[2] === 0x03 && data[3] === 0x04;
  if (isZip && data.includes("word/")) {
    return { ext: "docx", mime: "application/vnd.openxmlformats-officedocument.wordprocessingml.document" };
  }
  return null;
}
